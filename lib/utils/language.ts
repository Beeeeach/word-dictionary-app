/**
 * 投稿された単語が「英語の単語・フレーズ」とみなせるかを判定する。
 *
 * 用途:
 *  - 投稿フォーム: アルファベットのみの単語であれば、英和辞書API/翻訳APIを
 *    使った「意味を提案」ボタンを表示する（lib/actions/word-meaning.ts）。
 *  - 英語学習者モード: フィードを英語投稿のみにフィルタする際の判定にも
 *    同じロジックを使う（企画: アルファベットのみの投稿を自動で英語投稿とみなす）。
 *
 * 判定ルール:
 *  - 半角のアルファベット(a-zA-Z)・空白・基本的な記号(', -, .)のみで構成されている場合に true。
 *  - 日本語（ひらがな・カタカナ・漢字）や全角文字が1文字でも含まれる場合は false。
 *  - 空文字列は false（誤って「英語」と判定して不要な処理をしないため）。
 */
export function isAlphabeticWord(word: string): boolean {
  const trimmed = word.trim();
  if (!trimmed) return false;
  // 半角英字・空白・アポストロフィ・ハイフン・ピリオドのみを許可
  return /^[A-Za-z][A-Za-z\s'.\-]*$/.test(trimmed);
}
